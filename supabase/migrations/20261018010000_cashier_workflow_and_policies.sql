-- Responsibilities & Database Workflow:
-- 1. Customer places order -> Waiter reviews and approves.
-- 2. Customer submits payment proof -> Stored in private 'payment-proofs' storage.
-- 3. Cashier reviews payment proof via Cashier Portal:
--    - Revalidates cashier authorization via staff_profiles.
--    - Verifies proof against order total & payment amount.
--    - Approves: payment_reviews recorded, payment -> 'paid', order -> 'confirmed', status log & audit recorded.
--    - Rejects: payment_reviews recorded with required reason, payment -> 'failed', order -> 'rejected'.
-- ============================================================================

-- 1. Helper function to check if the authenticated user is an active Cashier or Admin
CREATE OR REPLACE FUNCTION public.is_active_cashier_or_admin()
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.staff_profiles
    WHERE user_id = auth.uid()
      AND role IN ('cashier', 'admin')
      AND is_active = true
  );
END;
$$;

-- 2. Ensure RLS is enabled on all payment workflow tables
ALTER TABLE public.staff_profiles   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_proofs   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_reviews  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_status_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_logs       ENABLE ROW LEVEL SECURITY;

-- 3. STAFF PROFILES Policies
-- Cashiers can read their own profile; admins can manage all profiles
DROP POLICY IF EXISTS "Cashiers can view own staff profile" ON public.staff_profiles;
CREATE POLICY "Cashiers can view own staff profile"
  ON public.staff_profiles FOR SELECT
  TO authenticated
  USING (user_id = auth.uid() OR public.is_active_cashier_or_admin());

-- 4. PAYMENT PROOFS Policies
-- Cashiers can read pending and reviewed payment proofs
DROP POLICY IF EXISTS "Cashiers can read payment proofs" ON public.payment_proofs;
CREATE POLICY "Cashiers can read payment proofs"
  ON public.payment_proofs FOR SELECT
  TO authenticated
  USING (
    public.is_active_cashier_or_admin()
    OR submitted_by = auth.uid()
  );

-- Cashiers can update payment proofs during review
DROP POLICY IF EXISTS "Cashiers can update payment proofs" ON public.payment_proofs;
CREATE POLICY "Cashiers can update payment proofs"
  ON public.payment_proofs FOR UPDATE
  TO authenticated
  USING (public.is_active_cashier_or_admin())
  WITH CHECK (public.is_active_cashier_or_admin());

-- 5. PAYMENT REVIEWS Policies
-- Cashiers can insert reviews (approved or rejected)
DROP POLICY IF EXISTS "Cashiers can insert payment reviews" ON public.payment_reviews;
CREATE POLICY "Cashiers can insert payment reviews"
  ON public.payment_reviews FOR INSERT
  TO authenticated
  WITH CHECK (
    public.is_active_cashier_or_admin()
    AND cashier_id = auth.uid()
  );

-- Cashiers can view review history
DROP POLICY IF EXISTS "Cashiers can view payment reviews" ON public.payment_reviews;
CREATE POLICY "Cashiers can view payment reviews"
  ON public.payment_reviews FOR SELECT
  TO authenticated
  USING (public.is_active_cashier_or_admin());

-- 6. ORDER STATUS LOGS Policies
DROP POLICY IF EXISTS "Cashiers can insert order status logs" ON public.order_status_logs;
CREATE POLICY "Cashiers can insert order status logs"
  ON public.order_status_logs FOR INSERT
  TO authenticated
  WITH CHECK (public.is_active_cashier_or_admin());

DROP POLICY IF EXISTS "Cashiers can read order status logs" ON public.order_status_logs;
CREATE POLICY "Cashiers can read order status logs"
  ON public.order_status_logs FOR SELECT
  TO authenticated
  USING (public.is_active_cashier_or_admin());

-- 7. NOTIFICATIONS Policies
DROP POLICY IF EXISTS "Staff can read notifications" ON public.notifications;
CREATE POLICY "Staff can read notifications"
  ON public.notifications FOR SELECT
  TO authenticated
  USING (
    recipient_user_id = auth.uid()
    OR public.is_active_cashier_or_admin()
  );

DROP POLICY IF EXISTS "Staff can update own notifications" ON public.notifications;
CREATE POLICY "Staff can update own notifications"
  ON public.notifications FOR UPDATE
  TO authenticated
  USING (recipient_user_id = auth.uid())
  WITH CHECK (recipient_user_id = auth.uid());

